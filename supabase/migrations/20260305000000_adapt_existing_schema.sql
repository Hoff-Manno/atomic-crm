-- 5. Update contacts_summary to include legacy customers
-- ---------------------------------------------------------------------------
DROP VIEW IF EXISTS contacts_summary;

CREATE VIEW contacts_summary AS
-- Existing CRM contacts
SELECT
    co.id,
    co.first_name,
    co.last_name,
    co.gender,
    co.title,
    co.email_jsonb,
    jsonb_path_query_array(co.email_jsonb, '$[*].email')::text AS email_fts,
    co.phone_jsonb,
    jsonb_path_query_array(co.phone_jsonb, '$[*].number')::text AS phone_fts,
    co.background,
    co.avatar,
    co.first_seen,
    co.last_seen,
    co.has_newsletter,
    co.status,
    co.tags,
    co.company_id,
    co.sales_id,
    co.linkedin_url,
    co.preferred_contact_method,
    co.date_of_birth,
    c.name AS company_name,
    COUNT(DISTINCT t.id) AS nb_tasks,
    'new'::text AS source
FROM contacts co
LEFT JOIN tasks t ON co.id = t.contact_id AND t.done_date IS NULL
LEFT JOIN companies c ON co.company_id = c.id
GROUP BY co.id, c.name

UNION ALL

-- Legacy customers extracted from dispatch_report
SELECT
    lc.id,
    lc.first_name,
    lc.last_name,
    NULL::text AS gender,
    NULL::text AS title,
    lc.email_jsonb,
    lc.email_fts,
    lc.phone_jsonb,
    lc.phone_fts,
    lc.background,
    NULL::jsonb AS avatar,
    lc.first_seen,
    lc.first_seen AS last_seen,
    false AS has_newsletter,
    'active'::text AS status,
    ARRAY[]::bigint[] AS tags,
    NULL::bigint AS company_id,
    NULL::bigint AS sales_id,
    NULL::text AS linkedin_url,
    'phone'::text AS preferred_contact_method,
    lc.date_of_birth,
    NULL::text AS company_name,
    0::bigint AS nb_tasks,
    'legacy'::text AS source
FROM (
    SELECT DISTINCT ON (dedup_key)
        (2000000 + ROW_NUMBER() OVER (ORDER BY MIN(dr.id)))::bigint AS id,
        -- Parse "Last, First" into first_name / last_name
        CASE
            WHEN POSITION(',' IN dr.customer_name) > 0
            THEN TRIM(SUBSTRING(dr.customer_name FROM POSITION(',' IN dr.customer_name) + 1))
            ELSE dr.customer_name
        END AS first_name,
        CASE
            WHEN POSITION(',' IN dr.customer_name) > 0
            THEN TRIM(SUBSTRING(dr.customer_name FOR POSITION(',' IN dr.customer_name) - 1))
            ELSE ''
        END AS last_name,
        -- Email as JSONB array
        CASE
            WHEN dr.customer_email IS NOT NULL AND dr.customer_email != ''
            THEN jsonb_build_array(jsonb_build_object('email', dr.customer_email, 'type', 'Home'))
            ELSE '[]'::jsonb
        END AS email_jsonb,
        COALESCE(dr.customer_email, '') AS email_fts,
        -- Phone numbers as JSONB array
        (
            SELECT COALESCE(jsonb_agg(phone_entry), '[]'::jsonb)
            FROM (
                SELECT jsonb_build_object('number', dr.customer_phone, 'type', 'Home') AS phone_entry
                WHERE dr.customer_phone IS NOT NULL AND dr.customer_phone != ''
                UNION ALL
                SELECT jsonb_build_object('number', dr.customer_mobile, 'type', 'Mobile')
                WHERE dr.customer_mobile IS NOT NULL AND dr.customer_mobile != ''
            ) phones
        ) AS phone_jsonb,
        COALESCE(dr.customer_phone, '') || ' ' || COALESCE(dr.customer_mobile, '') AS phone_fts,
        -- Address as background
        NULLIF(CONCAT_WS(', ',
            NULLIF(dr.customer_address, ''),
            NULLIF(dr.customer_suburb, ''),
            NULLIF(dr.customer_city, ''),
            NULLIF(dr.customer_postcode, '')
        ), '') AS background,
        parse_ddmmyyyy(dr.customer_dob::text) AS date_of_birth,
        COALESCE(parse_ddmmyyyy(dr.date_opened::text), dr.uploaded_at)::timestamptz AS first_seen,
        -- Deduplication key
        COALESCE(
            NULLIF(dr.customer_email, ''),
            dr.customer_name || '|' || COALESCE(dr.customer_phone, '')
        ) AS dedup_key
    FROM dispatch_report dr
    WHERE dr.customer_name IS NOT NULL AND dr.customer_name != ''
    GROUP BY
        dedup_key,
        dr.customer_name,
        dr.customer_email,
        dr.customer_phone,
        dr.customer_mobile,
        dr.customer_address,
        dr.customer_suburb,
        dr.customer_city,
        dr.customer_postcode,
        dr.customer_dob,
        dr.date_opened,
        dr.uploaded_at
    ORDER BY dedup_key, MIN(dr.id)
) lc;

