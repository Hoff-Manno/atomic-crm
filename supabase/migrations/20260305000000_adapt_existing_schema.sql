-- Re-attach triggers to crm_payments
CREATE OR REPLACE FUNCTION update_deal_payment_totals()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    deal_total_paid bigint;
    deal_amount bigint;
    current_stage text;
BEGIN
    SELECT COALESCE(SUM(p.amount), 0) INTO deal_total_paid
    FROM crm_payments p
    WHERE p.deal_id = COALESCE(NEW.deal_id, OLD.deal_id);

    SELECT d.amount, d.stage INTO deal_amount, current_stage
    FROM deals d
    WHERE d.id = COALESCE(NEW.deal_id, OLD.deal_id);

    UPDATE deals
    SET total_paid = deal_total_paid,
        stage = CASE
            WHEN deal_total_paid >= deal_amount
                AND current_stage IN ('new', 'deposit-paid', 'in-progress')
                THEN 'paid-in-full'
            WHEN deal_total_paid > 0
                AND deal_total_paid < deal_amount
                AND current_stage IN ('new', 'deposit-paid')
                THEN 'in-progress'
            ELSE current_stage
        END
    WHERE id = COALESCE(NEW.deal_id, OLD.deal_id);

    RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS update_deal_totals_on_insert ON crm_payments;
CREATE TRIGGER update_deal_totals_on_insert
AFTER INSERT ON crm_payments FOR EACH ROW EXECUTE FUNCTION update_deal_payment_totals();

DROP TRIGGER IF EXISTS update_deal_totals_on_update ON crm_payments;
CREATE TRIGGER update_deal_totals_on_update
AFTER UPDATE ON crm_payments FOR EACH ROW EXECUTE FUNCTION update_deal_payment_totals();

DROP TRIGGER IF EXISTS update_deal_totals_on_delete ON crm_payments;
CREATE TRIGGER update_deal_totals_on_delete
AFTER DELETE ON crm_payments FOR EACH ROW EXECUTE FUNCTION update_deal_payment_totals();

